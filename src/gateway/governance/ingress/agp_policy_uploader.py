"""
AGP Policy Uploader (C2)
========================

Calls the Google Agent Platform API to create or update a Semantic Governance
Policy (SGP) resource using the natural language constraint text generated by
``stpa_compiler.generate_agp()``.

This module is GCP-specific and optional — operators on other platforms skip
this step. The ``gcloud beta ai semantic-governance-policies`` CLI is the
confirmed interface as of 2026-07.

The exact Python SDK method for SGP creation must be verified against
``google-cloud-aiplatform`` at implementation time; this module provides a
best-effort implementation using the REST API directly via ``google-auth``.

Usage::

    from src.gateway.governance.ingress.agp_policy_uploader import upload_agp_policy

    policy_name = upload_agp_policy(
        project="my-gcp-project",
        location="us-central1",
        policy_text_path="config/agp/generated_semantic_policy.txt",
    )
    print(f"Policy resource: {policy_name}")

Environment variables:
    GOOGLE_CLOUD_PROJECT — GCP project ID (required if not passed explicitly)
    GOOGLE_CLOUD_LOCATION — GCP region (default: us-central1)
    CAGE_AGP_POLICY_ID — existing policy ID to update (optional; creates new if absent)
"""

from __future__ import annotations

import logging
import os
from collections.abc import Awaitable, Callable, Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

from src.gateway.governance.ingress.agent_registry_adapter import RegistryCatalog

logger = logging.getLogger("Gateway.Governance.Ingress.AGPPolicyUploader")

# Default AGP output path (mirrors stpa_compiler._DEFAULT_AGP_OUT)
_REPO_ROOT = Path(__file__).resolve().parents[4]
_DEFAULT_AGP_OUT = _REPO_ROOT / "config" / "agp" / "generated_semantic_policy.txt"

# AGP character budget (must match stpa_compiler._AGP_CHAR_BUDGET)
_AGP_CHAR_BUDGET = 5_000

# AGP API base URL (Vertex AI Agent Platform)
_AGP_API_BASE = "https://{location}-aiplatform.googleapis.com/v1beta1"

CerArtifactVerifier = Callable[[Mapping[str, Any]], Awaitable[tuple[bool, str]]]
"""Async seam that cryptographically verifies one skill ``.cer`` artifact.

Returns ``(verified, reason)``. Integrators inject a closure over the offline
plane's ``.cer`` verifier that resolves signing keys out-of-band by ``kid`` and
supplies the ``SKILL.md`` bytes the artifact must certify. Only ``verified is
True`` counts as success; an exception counts as a failure.
"""


def _extract_host(url_or_host: str) -> str:
    """Extract normalized hostname from a URL or bare host string."""
    val = url_or_host.strip()
    if not val:
        return ""
    if "://" in val:
        return (urlparse(val).hostname or "").lower()
    # Strip optional port/path if bare host:port/path
    return (urlparse(f"https://{val}").hostname or "").lower()


@dataclass(frozen=True)
class GatewayEnforcementTransitionResult:
    """Result of evaluating GEAP Agent Gateway ``DRY_RUN`` -> ``ENFORCED`` readiness.

    Attributes:
        gateway_id: Identifier of the GEAP Agent Gateway resource.
        previous_mode: Mode prior to evaluation (typically ``DRY_RUN``).
        effective_mode: Resulting mode (``ENFORCED`` only when all gates pass;
            otherwise remains ``DRY_RUN``).
        transition_allowed: True iff inventory, IAP CEL bindings, and ``.cer``
            certifications all passed.
        unregistered_targets: Outbound targets observed in dry-run logs that
            are not registered in the ``RegistryCatalog``.
        missing_iap_bindings: Targets lacking a valid ``roles/iap.egressor``
            binding or required CEL condition.
        cer_verified: True iff a ``cer_verifier`` was supplied and every
            provided skill ``.cer`` artifact (at least one) passed it.
        blocking_reasons: Human-readable list of fail-closed blockers.
    """

    gateway_id: str
    previous_mode: str
    effective_mode: str
    transition_allowed: bool
    unregistered_targets: tuple[str, ...] = field(default_factory=tuple)
    missing_iap_bindings: tuple[str, ...] = field(default_factory=tuple)
    cer_verified: bool = False
    blocking_reasons: tuple[str, ...] = field(default_factory=tuple)


async def verify_and_transition_gateway_mode(
    gateway_id: str,
    discovered_targets: list[str],
    catalog: RegistryCatalog,
    iap_bindings: list[dict[str, Any]],
    *,
    current_mode: str = "DRY_RUN",
    require_cel_conditions: bool = True,
    cer_artifacts: Sequence[Mapping[str, Any]] | None = None,
    cer_verifier: CerArtifactVerifier | None = None,
) -> GatewayEnforcementTransitionResult:
    """Gate the GEAP 4-step ``DRY_RUN`` -> ``ENFORCED`` Agent Gateway transition.

    Enforces three fail-closed preconditions before flipping a GEAP Agent
    Gateway from observation (``DRY_RUN``) to active blocking (``ENFORCED``):

      1. **Registry Coverage**: Every target in ``discovered_targets`` (from
         Cloud Logging ``gapi.core.services`` / MCP egress logs) must match a
         registered MCP server, endpoint destination URL/ID, or agent in
         ``catalog``.
      2. **IAM + CEL Egress Binding**: Every discovered target must have an
         explicit ``roles/iap.egressor`` binding in ``iap_bindings`` with at
         least one ``principal://`` or ``principalSet://`` member and (when
         ``require_cel_conditions=True``) a non-empty CEL ``condition.expression``.
      3. **Skill Certification (``.cer``)**: a ``cer_verifier`` must be
         supplied, at least one ``cer_artifacts`` entry must be provided, and
         every artifact must pass the verifier. A missing verifier, a missing
         artifact, a refusal, or a verifier exception is a blocking reason;
         there is no presence-only fallback.
    """
    blocking_reasons: list[str] = []

    if not catalog.is_valid:
        blocking_reasons.append(
            f"RegistryCatalog is invalid or empty (error={catalog.error!r})."
        )

    # Collect all registered identifiers and exact parsed hostnames/URLs from the catalog
    registered_tokens: set[str] = set()
    registered_hosts: set[str] = set()

    def _register_url_or_token(token_str: str, *, is_url: bool = False) -> None:
        cleaned = token_str.strip()
        if not cleaned:
            return
        registered_tokens.add(cleaned)
        if is_url or "://" in cleaned:
            host = _extract_host(cleaned)
            if host:
                registered_hosts.add(host)

    for agent_id, agent_data in catalog.agents.items():
        _register_url_or_token(agent_id)
        if isinstance(agent_data, dict) and agent_data.get("registry_resource_name"):
            _register_url_or_token(str(agent_data["registry_resource_name"]))

    for srv_id, srv_data in catalog.mcp_servers.items():
        _register_url_or_token(srv_id)
        if isinstance(srv_data, dict):
            if srv_data.get("registry_resource_name"):
                _register_url_or_token(str(srv_data["registry_resource_name"]))
            for iface in srv_data.get("interfaces", []):
                if isinstance(iface, dict) and iface.get("url"):
                    _register_url_or_token(str(iface["url"]), is_url=True)
                elif isinstance(iface, str):
                    _register_url_or_token(iface, is_url=True)

    for ep_id, ep_data in catalog.endpoints.items():
        _register_url_or_token(ep_id)
        if isinstance(ep_data, dict):
            if ep_data.get("registry_resource_name"):
                _register_url_or_token(str(ep_data["registry_resource_name"]))
            for url in ep_data.get("destination_urls", []):
                _register_url_or_token(str(url), is_url=True)

    def _is_target_registered(target: str) -> bool:
        cleaned = target.strip()
        if not cleaned:
            return False
        if cleaned in registered_tokens:
            return True
        target_host = _extract_host(cleaned)
        return bool(target_host and target_host in registered_hosts)

    unregistered: list[str] = []
    for target in discovered_targets:
        if not _is_target_registered(target):
            unregistered.append(target)

    if unregistered:
        blocking_reasons.append(
            f"Unregistered outbound targets discovered in DRY_RUN logs: {unregistered}"
        )

    # Check roles/iap.egressor bindings per discovered target
    missing_bindings: list[str] = []
    for target in discovered_targets:
        matched_valid_binding = False
        target_host = _extract_host(target)
        for binding in iap_bindings:
            if not isinstance(binding, dict):
                continue
            if binding.get("role") != "roles/iap.egressor":
                continue
            b_target = str(
                binding.get("target") or binding.get("resource") or ""
            ).strip()
            if not b_target:
                continue
            if b_target != "*" and b_target != target:
                b_host = _extract_host(b_target)
                if not (target_host and b_host and target_host == b_host):
                    continue
            members = binding.get("members", [])
            has_agent_principal = isinstance(members, list) and any(
                isinstance(m, str)
                and m.startswith(("principal://", "principalSet://", "spiffe://"))
                for m in members
            )
            if not has_agent_principal:
                continue
            if require_cel_conditions:
                cond = binding.get("condition")
                expr = cond.get("expression", "") if isinstance(cond, dict) else ""
                if not isinstance(expr, str) or not expr.strip():
                    continue
            matched_valid_binding = True
            break

        if not matched_valid_binding:
            missing_bindings.append(target)

    if missing_bindings:
        blocking_reasons.append(
            "Missing valid roles/iap.egressor binding (or CEL condition) for targets: "
            f"{missing_bindings}"
        )

    # Check .cer skill certifications: cryptographic verification is mandatory.
    effective_cer_ok = True
    if cer_verifier is None:
        effective_cer_ok = False
        blocking_reasons.append(
            "No .cer verifier configured; skill certifications cannot be verified."
        )
    if not cer_artifacts:
        effective_cer_ok = False
        blocking_reasons.append("No .cer artifacts provided for verification.")
    elif cer_verifier is not None:
        for idx, artifact in enumerate(cer_artifacts):
            if not isinstance(artifact, Mapping):
                effective_cer_ok = False
                blocking_reasons.append(f".cer artifact[{idx}] is not a mapping.")
                continue
            try:
                ok, reason = await cer_verifier(artifact)
            except Exception as exc:
                effective_cer_ok = False
                logger.warning(
                    ".cer verifier raised %s for artifact[%d]", type(exc).__name__, idx
                )
                blocking_reasons.append(
                    f".cer artifact[{idx}] verifier raised {type(exc).__name__}."
                )
                continue
            if ok is not True:
                effective_cer_ok = False
                blocking_reasons.append(
                    f".cer artifact[{idx}] failed verifier: {reason}"
                )

    transition_allowed = (
        catalog.is_valid
        and not unregistered
        and not missing_bindings
        and effective_cer_ok
        and not blocking_reasons
    )
    effective_mode = "ENFORCED" if transition_allowed else "DRY_RUN"

    return GatewayEnforcementTransitionResult(
        gateway_id=gateway_id,
        previous_mode=current_mode,
        effective_mode=effective_mode,
        transition_allowed=transition_allowed,
        unregistered_targets=tuple(unregistered),
        missing_iap_bindings=tuple(missing_bindings),
        cer_verified=effective_cer_ok,
        blocking_reasons=tuple(blocking_reasons),
    )


def _get_credentials() -> Any:
    """Obtain Google Cloud credentials via Application Default Credentials."""
    try:
        import google.auth
        import google.auth.transport.requests

        credentials, project = google.auth.default(
            scopes=["https://www.googleapis.com/auth/cloud-platform"]
        )
        return credentials, project
    except ImportError:
        raise RuntimeError(
            "AGPPolicyUploader: google-auth is not installed. "
            "Install it with: pip install google-auth"
        )
    except Exception as exc:
        raise RuntimeError(
            f"AGPPolicyUploader: failed to obtain Google Cloud credentials: {exc}. "
            "Ensure Application Default Credentials are configured: "
            "gcloud auth application-default login"
        ) from exc


def _validate_policy_text(policy_text: str) -> None:
    """Validate the policy text before upload."""
    if not policy_text.strip():
        raise ValueError("AGPPolicyUploader: policy text is empty.")
    if len(policy_text) > _AGP_CHAR_BUDGET:
        raise ValueError(
            f"AGPPolicyUploader: policy text exceeds {_AGP_CHAR_BUDGET}-character AGP budget "
            f"({len(policy_text)} chars). Truncate before uploading."
        )
    if "# TRUNCATED" in policy_text:
        raise ValueError(
            "AGPPolicyUploader: policy text contains TRUNCATED sentinel — "
            "the text was truncated by the compiler and cannot be uploaded as-is."
        )


def upload_agp_policy(
    policy_text: str | None = None,
    policy_text_path: str | Path | None = None,
    project: str | None = None,
    location: str | None = None,
    policy_id: str | None = None,
    display_name: str = "CAGE STPA Semantic Governance Policy",
    dry_run: bool = False,
) -> str:
    """Upload or update an AGP Semantic Governance Policy.

    Args:
        policy_text: The natural language constraint text to upload.
                     If None, reads from ``policy_text_path``.
        policy_text_path: Path to the generated policy text file.
                          Defaults to ``config/agp/generated_semantic_policy.txt``.
        project: GCP project ID. Defaults to ``GOOGLE_CLOUD_PROJECT`` env var.
        location: GCP region. Defaults to ``GOOGLE_CLOUD_LOCATION`` env var or
                  ``us-central1``.
        policy_id: Existing policy resource ID to update. If None, creates a new
                   policy. Defaults to ``CAGE_AGP_POLICY_ID`` env var.
        display_name: Human-readable display name for the policy resource.
        dry_run: If True, validates the policy text but does not call the API.

    Returns:
        The policy resource name (e.g.
        ``projects/my-project/locations/us-central1/semanticGovernancePolicies/my-policy``).

    Raises:
        ValueError: If policy text is invalid (empty, too long, or truncated).
        RuntimeError: If GCP credentials cannot be obtained or the API call fails.
    """
    # Resolve policy text
    if policy_text is None:
        effective_path = Path(policy_text_path or _DEFAULT_AGP_OUT)
        if not effective_path.exists():
            raise FileNotFoundError(
                f"AGPPolicyUploader: policy text file not found: {effective_path}. "
                "Run: python -m src.gateway.governance.stpa_compiler compile --targets agp"
            )
        policy_text = effective_path.read_text(encoding="utf-8")
        logger.info("AGPPolicyUploader: loaded policy text from %s", effective_path)

    # Validate
    _validate_policy_text(policy_text)
    char_count = len(policy_text)
    logger.info(
        "AGPPolicyUploader: policy text validated (%d/%d chars).",
        char_count,
        _AGP_CHAR_BUDGET,
    )

    # Resolve GCP config
    effective_project = project or os.environ.get("GOOGLE_CLOUD_PROJECT")
    if not effective_project:
        raise RuntimeError(
            "AGPPolicyUploader: GCP project not specified. "
            "Set GOOGLE_CLOUD_PROJECT environment variable or pass project= argument."
        )
    effective_location = location or os.environ.get(
        "GOOGLE_CLOUD_LOCATION", "us-central1"
    )
    effective_policy_id = policy_id or os.environ.get("CAGE_AGP_POLICY_ID")

    if dry_run:
        logger.info(
            "AGPPolicyUploader: dry-run mode — would upload %d chars to "
            "project=%s location=%s policy_id=%s",
            char_count,
            effective_project,
            effective_location,
            effective_policy_id or "(new)",
        )
        return f"projects/{effective_project}/locations/{effective_location}/semanticGovernancePolicies/dry-run"

    # Build API request
    api_base = _AGP_API_BASE.format(location=effective_location)
    parent = f"projects/{effective_project}/locations/{effective_location}"

    policy_body: dict[str, Any] = {
        "displayName": display_name,
        "constraints": policy_text,
    }

    try:
        import google.auth.transport.requests
        import requests as _requests

        credentials, _ = _get_credentials()
        auth_req = google.auth.transport.requests.Request()
        credentials.refresh(auth_req)
        headers = {
            "Authorization": f"Bearer {credentials.token}",
            "Content-Type": "application/json",
        }

        if effective_policy_id:
            # Update existing policy
            url = (
                f"{api_base}/{parent}/semanticGovernancePolicies/{effective_policy_id}"
            )
            response = _requests.patch(
                url, json=policy_body, headers=headers, timeout=30
            )
            operation = "updated"
        else:
            # Create new policy
            url = f"{api_base}/{parent}/semanticGovernancePolicies"
            response = _requests.post(
                url, json=policy_body, headers=headers, timeout=30
            )
            operation = "created"

        response.raise_for_status()
        result = response.json()
        resource_name = result.get(
            "name", f"{parent}/semanticGovernancePolicies/unknown"
        )

        logger.info(
            "AGPPolicyUploader: policy %s successfully. resource=%s",
            operation,
            resource_name,
        )
        return resource_name

    except ImportError:
        raise RuntimeError(
            "AGPPolicyUploader: 'requests' library is not installed. "
            "Install it with: pip install requests google-auth"
        )
    except Exception as exc:
        raise RuntimeError(
            f"AGPPolicyUploader: API call failed: {exc}. "
            "Verify GCP credentials and that the Agent Platform API is enabled."
        ) from exc
