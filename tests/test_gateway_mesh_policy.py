def _render_mesh_policy_chart(
    trusted_identities: list[str] | None = None,
    namespace: str = "governance-stack",
    canary_identities: list[str] | None = None,
) -> list[dict]:
    """Deterministically render infra/modules/gateway/mesh-policy/templates/policy.yaml."""
    values = yaml.safe_load((_CHART / "values.yaml").read_text(encoding="utf-8"))
    open_paths: list[str] = list(values["openExactPaths"])
    identities: list[str] = (
        list(values["trustedIdentities"])
        if trusted_identities is None
        else list(trusted_identities)
    )
    canaries: list[str] = (
        list(values.get("canaryIdentities", []))
        if canary_identities is None
        else list(canary_identities)
    )
    tpl = (_CHART / "templates" / "policy.yaml").read_text(encoding="utf-8")
    rendered = tpl.replace("{{ .Release.Namespace }}", namespace)

    open_block = "".join(
        f"        - path:\n            type: Exact\n            value: {json_or_quote}\n"
        for json_or_quote in [f'"{p}"' for p in open_paths]
    )
    rendered = re.sub(
        r"\{\{- range \.Values\.openExactPaths \}\}.*?\{\{- end \}\}\n",
        open_block,
        rendered,
        flags=re.S,
    )

    id_block = "".join(f'    - "{ident}"\n' for ident in identities)
    rendered = re.sub(
        r"\{\{- range \.Values\.trustedIdentities \}\}.*?\{\{- end \}\}\n",
        id_block,
        rendered,
        flags=re.S,
    )
    if identities:
        rendered = re.sub(
            r"\{\{- if \.Values\.trustedIdentities \}\}\n(.*?)\{\{- end \}\}",
            r"\1",
            rendered,
            flags=re.S,
        )
    else:
        rendered = re.sub(
            r"\{\{- if \.Values\.trustedIdentities \}\}\n.*?\{\{- end \}\}",
            "",
            rendered,
            flags=re.S,
        )

    canary_block = "".join(f'    - "{ident}"\n' for ident in canaries)
    rendered = re.sub(
        r"\{\{- range \.Values\.canaryIdentities \}\}.*?\{\{- end \}\}\n",
        canary_block,
        rendered,
        flags=re.S,
    )
    if canaries:
        rendered = re.sub(
            r"\{\{- if \.Values\.canaryIdentities \}\}\n(.*?)\{\{- end \}\}",
            r"\1",
            rendered,
            flags=re.S,
        )
    else:
        rendered = re.sub(
            r"\{\{- if \.Values\.canaryIdentities \}\}\n.*?\{\{- end \}\}",
            "",
            rendered,
            flags=re.S,
        )
    return [d for d in yaml.safe_load_all(rendered) if isinstance(d, dict)]


def _by(docs: list[dict], kind: str, name: str) -> dict:
    matches = [d for d in docs if d["kind"] == kind and d["metadata"]["name"] == name]
    assert len(matches) == 1, f"expected one {kind}/{name}, found {len(matches)}"
    return matches[0]


def open_route_paths(route: dict) -> set[str]:
    """Exact paths of an open HTTPRoute. Only exact paths may be open: a
    prefix (of any method) would open a route family, so it is rejected."""
    exact: set[str] = set()
    for rule in route["spec"]["rules"]:
        for match in rule["matches"]:
            path = match["path"]
            if path["type"] == "Exact":
                exact.add(path["value"])
            else:
                raise AssertionError(f"open route may only hold Exact paths: {match}")
    return exact


def gateway_policy_violations(docs: list[dict]) -> list[str]:
    """Every way the rendered gateway policy can drift from the app's policy."""
    problems: list[str] = []
    exact = open_route_paths(_by(docs, "HTTPRoute", "gateway-open"))
    if exact != set(OPEN_EXACT_PATHS):
        problems.append(
            f"open exact paths {sorted(exact)} != app {sorted(OPEN_EXACT_PATHS)}"
        )

    gated = _by(docs, "HTTPRoute", "gateway-gated")
    matches = [m for r in gated["spec"]["rules"] for m in r["matches"]]
    if matches != [{"path": {"type": "PathPrefix", "value": "/"}}]:
        problems.append(f"gated route must be exactly PathPrefix '/', got {matches}")

    policy = _by(docs, "AuthorizationPolicy", "gateway-gated")
    if policy["spec"]["targetRef"] != {
        "group": "policy.linkerd.io",
        "kind": "HTTPRoute",
        "name": "gateway-gated",
    }:
        problems.append(f"gateway-gated policy targets {policy['spec']['targetRef']}")
    refs = policy["spec"]["requiredAuthenticationRefs"]
    if [r["kind"] for r in refs] != ["MeshTLSAuthentication"]:
        problems.append(f"gated route must require mesh identity only, got {refs}")
    else:
        identities = set(
            _by(docs, "MeshTLSAuthentication", refs[0]["name"])["spec"]["identities"]
        )
        if identities != {ADVISOR_IDENTITY}:
            problems.append(f"gated identities {sorted(identities)} != {{advisor}}")
    return problems


def served_version_violations(text: str) -> list[str]:
    """Linkerd policy objects whose apiVersion edge-26.9.3 does not serve."""
    out = []
    for version, kind in re.findall(
        r"apiVersion:\s*policy\.linkerd\.io/(\w+)\s*\nkind:\s*(\w+)", text
    ):
        if kind in _SERVED and version not in _SERVED[kind]:
            out.append(f"{kind} policy.linkerd.io/{version}")
    return out


