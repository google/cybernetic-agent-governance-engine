"""POAM-2026-080: the mesh half of the gateway's ingress check.

The gateway admits a caller in two places: the Linkerd proxy
(Server/HTTPRoute/AuthorizationPolicy) and the app
(``WorkloadIdentityMiddleware``). These tests keep the two layers, the raw
manifests and the Terraform path describing the same policy:

* the open paths are identical everywhere;
* everything else is gated to the advisor's mesh identity only;
* Linkerd policy objects use API versions that Linkerd edge-26.9.3 serves;
* no CA private key is generated by Terraform (it would sit in state);
* no ingress HMAC secret is wired into any deployment path.
"""

