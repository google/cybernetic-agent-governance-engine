"""Outcome independence: the causal tier must recover the world's structure,
not replay the formula it was calibrated on (POAM-2026-094).

The gatekeeper estimates ``beta``, the effect of the treatment on the outcome,
and the per-request boundary predicts from it. That is only informative if the
outcome comes from a process the system did not write down in advance. Today
both telemetry sources the tier can be wired to -- ``generate_mock_telemetry``
(the finance plugin's ``synthetic_telemetry_factory``, permitted in every
non-enforcing posture) and the kernel's ``MockTelemetryProvider`` -- emit the
*calibration formula* ``risk_score = 0.5 * vol + 0.5 * amount / 1e4 +
N(0, 0.05)``: the process the boundary and placebo tests were calibrated on
(fitted ``beta`` 0.4921, trip point $9,143.93). Against such a source the
estimator can only reproduce a constant it was given.

Two different 0.5s are in play. The calibration formula's coefficients (0
intercept, 0.5 per unit of volatility, 0.5 per $10,000) are what this module
detects. ``_marginal_risk``'s ``0.5 + beta * amount / scale`` uses an unrelated
0.5 baseline, which is neither estimated nor equal to the formula's intercept
(0) or its mean outcome at zero treatment (0.25). That baseline is a separate
enforcement finding. Nothing here tests it, and
``test_the_same_request_is_allowed_in_one_world_and_denied_in_the_other``
encodes it as current behaviour.

Three kinds of test live here, and they must be read differently:

1. **Recovery contract** (``test_estimator_recovers_*``, placebo, shuffle,
   same-request). Ground-truth processes whose coefficients deliberately differ
   from the calibration formula (0.8 vol / 0.2 amount and 0.3 vol / 0.6
   amount). These pass today. That is not a weakness: they prove the estimation
   path and the graph are sound, so a future red elsewhere is the data's fault,
   not dowhy's.
2. **Mutation checks** (``test_recovery_band_rejects_the_calibration_constant``,
   ``test_self_certification_detector_flags_the_calibration_world``). Not
   properties of the system. They show that the recovery band and the detector
   each reject a frame generated by the calibration formula, i.e. that tests 1
   and 3 discriminate. Do not read them as production guarantees.
3. **Self-certification detector**
   (``test_tier_telemetry_source_is_not_the_calibration_formula``). The real
   tripwire. For each source the tier can be wired to, fit the outcome on
   ``[1, market_volatility, trade_amount / scale]`` by ordinary least squares on
   the source's well-conditioned frame and require that the fitted coefficients
   are *not* all within ``_SELF_CERTIFICATION_Z`` standard errors of the
   calibration formula ``(0, 0.5, 0.5)``. Today both sources are within 1.73 SE
   on all three, so the test is a strict ``xfail`` under POAM-2026-094. When an
   outcome observer that reads a realised quantity (drawdown over a horizon off
   a price path) lands, the test passes, and **the marker is removed while the
   assertion stays** as the permanent guard against reintroducing a
   self-certifying outcome. Removal of the marker is the signal that
   POAM-2026-094 can close. The marker's ``raises=SelfCertifyingOutcome`` means
   it absorbs only that finding: a missing factory, a changed row count or a
   rank-deficient frame fails the test outright.

Why the detector is phrased this way and not on ``beta`` or on R²:

* A dowhy ``beta`` assertion against these sources would be numerically
  unstable where the design is ill-conditioned (finding F31: the same
  rank-deficient frame fits beta = +0.10 on Accelerate, -6.35e11 on
  OpenBLAS/Haswell and -6.51e11 on OpenBLAS/SkylakeX).
* An R² ceiling was tried first and **does not discriminate**: R² of the
  outcome on these regressors is 0.83 (finance synthetic, n = 1,000) and 0.81
  (kernel mock, n = 600), while an independent world in this module
  (``WORLD_B``, n = 600) measures 0.77. Any linear process with small noise has
  high R². Self-certification is not "the inputs explain a lot"; it is "the
  outcome *is* the calibration formula".
* Coefficient identity tests exactly that, and OLS on a three-column
  well-conditioned design gives coefficients, standard errors and z that are
  stable across BLAS builds to better than 1e-12 relative.

Calibration n. The 4-SE threshold is calibrated at ``_DETECTOR_N`` = 1,000
rows, the row count ``generate_mock_telemetry()`` returns when production calls
it, and the detector asserts that row count before fitting. Measured z against
n (2026-10-27, Linux x86_64, OpenBLAS Haswell): the two calibration-formula
sources stay at max |z| 0.25-2.34 for every n from 50 to 10,000, so there is no
systematic bias and a different n would not by itself turn the xfail into an
XPASS. The independent worlds grow roughly as sqrt(n), from 7.1 and 11.6 at
n = 50 (the tier's ``min_samples``) to 89.4 and 131.2 at n = 10,000. What the
pin protects is power: a future source whose coefficients lie near
(0, 0.5, 0.5) is resolved less sharply at small n.

Marginal, not joint. The criterion ANDs three marginal z-tests. The
coefficient estimates are correlated -- volatility confounds amount by
construction (finance synthetic at n = 1,000: corr(vol, amount) = +0.46,
corr(intercept, amount) = -0.91) -- so marginal standard errors do not describe
joint distance from (0, 0.5, 0.5). The principled form is the Wald statistic
``W = (b - b0)' Cov^-1 (b - b0) ~ chi2(3)``. Measured at n = 1,000: W = 5.35
(finance synthetic) and 1.80 (kernel mock), against 6,080 and 1,170 for the
independent worlds; the chi2(3) critical value at the family-wise level of the
4-SE marginal rule (p = 1.9e-4) is 19.76. Not adopted, because the marginal
form already separates by an order of magnitude; start here if it is ever
tightened.

Scope: one formula, not the class. An observer that emitted the same quantity
under a different parameterisation, or re-implemented a risk formula inline
with other constants, would pass. The G3 rule that stops the outcome-observer
package importing the risk-formula package (to be added) guards the import
route; an inline re-implementation is caught by neither. The class-level
property -- the outcome carries variance decided after the decision -- needs a
realistic control: this module's "independent" worlds are formula-shaped too, a
linear function of decision-time features plus small noise, which is why an R²
ceiling could not separate them from the calibration sources. A price-path
simulator would supply that control.

Tolerance provenance: ``_TOL`` was set at n = 600 on Linux x86_64 with OpenBLAS's
``Haswell`` kernel (AMD Zen 3), the platform class CI runs. CI's own kernel,
OpenBLAS ``SkylakeX`` on GitHub's Intel runners, validates it on this module's
first CI run. Widening ``_TOL`` afterwards is a deliberate act that needs a
recorded reason, not a reaction to a red run.
"""

