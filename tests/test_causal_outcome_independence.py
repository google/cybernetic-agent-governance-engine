import numpy as np
import pandas as pd
import pytest

pytest.importorskip("networkx", reason="networkx required by the causal gatekeeper")

from src.cage_finance.tiers.causal_tier import (
    build_finance_causal_gatekeeper,
    build_finance_causal_spec,
)
from src.gateway.governance.causal import gatekeeper as gk_mod
from src.gateway.governance.causal.gatekeeper import (
    CAUSAL_LOCK_RISK_BOUNDARY,
    CAUSAL_NORMALIZATION_SCALE,
    REASON_RISK_BOUNDARY,
    REASON_TRUSTED,
    validate_world_model,
)
from src.gateway.governance.telemetry_provider import MockTelemetryProvider

pytestmark = [
    pytest.mark.unit,
    pytest.mark.local,
    pytest.mark.skipif(not gk_mod._DOWHY_AVAILABLE, reason="dowhy not installed"),
]

_N = 600  # recovery-contract sample size; _TOL is set at this n
_SEED = 20261027
# The slope the existing boundary and placebo tests were calibrated on
# (risk per $10,000). 0.45 / 0.4921 * 10_000 = $9,143.93, the pinned trip point.
_CALIBRATION_BETA = 0.4921
# Estimator tolerance. Standard error at _N with these designs is ~0.015.
# See the module docstring for which BLAS kernels it was set on.
_TOL = 0.05
# The calibration formula as the OLS coefficients of risk_score on
# [1, market_volatility, trade_amount / scale] read it. Not _marginal_risk's
# 0.5 baseline, which is a different constant (see the module docstring).
_CALIBRATION_FORMULA = np.array([0.0, 0.5, 0.5])
# Detector threshold, and the row count it is calibrated at: what production
# gets from generate_mock_telemetry(). Calibration-formula sources sit at
# max |z| 1.73 and 1.11 there; the independent worlds at 28.6 and 40.7.
_SELF_CERTIFICATION_Z = 4.0
_DETECTOR_N = 1_000


@dataclass(frozen=True)
class GroundTruth:
    """A data-generating process with known coefficients."""

    vol_coef: float
    amount_coef: float  # outcome change per CAUSAL_NORMALIZATION_SCALE of amount
    noise_sd: float = 0.05


# Both differ from the calibration formula (0.5 / 0.5) by more than _TOL.
WORLD_A = GroundTruth(vol_coef=0.8, amount_coef=0.2)
WORLD_B = GroundTruth(vol_coef=0.3, amount_coef=0.6)
# The calibration formula itself, used only by the mutation checks.
CALIBRATION_WORLD = GroundTruth(vol_coef=0.5, amount_coef=0.5)


def reference_world(
    truth: GroundTruth, *, n: int = _N, seed: int = _SEED
) -> pd.DataFrame:
    """Rows from ``truth``. Volatility confounds amount and outcome."""
    rng = np.random.default_rng(seed)
    vol = rng.uniform(0.1, 0.9, n)
    amount = np.clip(rng.normal(5000.0, 1500.0, n) - vol * 2000.0, 100.0, 10_000.0)
    outcome = (
        0.05
        + truth.vol_coef * vol
        + truth.amount_coef * amount / CAUSAL_NORMALIZATION_SCALE
        + rng.normal(0.0, truth.noise_sd, n)
    )
    return pd.DataFrame(
        {
            "market_volatility": vol,
            "trade_amount": amount,
            "risk_score": outcome,
            "timestamp": time.time() - rng.uniform(0.0, 60.0, n),
        }
    )


def _fit(frame: pd.DataFrame):  # type: ignore[no-untyped-def]
    spec = build_finance_causal_spec()
    return validate_world_model(
        spec.graph_dot,
        spec.treatment_col,
        spec.outcome_col,
        frame,
        normalization_scale=spec.normalization_scale,
    )


class SelfCertifyingOutcome(AssertionError):
    """The source's outcome column is the calibration formula."""


@dataclass(frozen=True)
class FormulaDistance:
    """How far a source's outcome is from the calibration formula."""

    coef: np.ndarray  # (intercept, per-volatility, per-scale-of-amount)
    se: np.ndarray
    z: np.ndarray  # (coef - _CALIBRATION_FORMULA) / se
    r_squared: float  # reported for context; not asserted on (see module doc)

    @property
    def is_calibration_formula(self) -> bool:
        return bool(np.all(np.abs(self.z) < _SELF_CERTIFICATION_Z))


def calibration_formula_distance(frame: pd.DataFrame) -> FormulaDistance:
    """OLS of ``risk_score`` on ``[1, market_volatility, trade_amount / scale]``.

    A well-conditioned design: three columns, no constant treatment, no
    collinearity. Raises ``ValueError`` -- not an assertion, so the detector's
    xfail cannot absorb it -- if the design is rank-deficient.
    """
    y = frame["risk_score"].to_numpy(dtype=float)
    design = np.column_stack(
        [
            np.ones(len(frame)),
            frame["market_volatility"].to_numpy(dtype=float),
            frame["trade_amount"].to_numpy(dtype=float) / CAUSAL_NORMALIZATION_SCALE,
        ]
    )
    n, k = design.shape
    rank = np.linalg.matrix_rank(design)
    if rank != k:
        raise ValueError(f"design is rank-deficient ({rank} < {k}); fit undefined")
    coef, *_ = np.linalg.lstsq(design, y, rcond=None)
    residual = y - design @ coef
    sigma2 = float(residual @ residual) / (n - k)
    se = np.sqrt(np.diag(sigma2 * np.linalg.inv(design.T @ design)))
    total = y - y.mean()
    r_squared = 1.0 - float(residual @ residual) / float(total @ total)
    return FormulaDistance(
        coef=coef, se=se, z=(coef - _CALIBRATION_FORMULA) / se, r_squared=r_squared
    )


