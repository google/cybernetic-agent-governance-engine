@pytest.mark.parametrize("truth", [WORLD_A, WORLD_B], ids=["0.8/0.2", "0.3/0.6"])
def test_estimator_recovers_the_worlds_coefficient_not_the_calibration(
    truth: GroundTruth,
) -> None:
    verdict = _fit(reference_world(truth))
    assert verdict.trusted, verdict.reason
    assert verdict.beta is not None
    assert abs(verdict.beta - truth.amount_coef) < _TOL
    assert abs(verdict.beta - _CALIBRATION_BETA) > _TOL


def test_zero_effect_placebo_treatment_estimates_no_effect() -> None:
    frame = reference_world(WORLD_A)
    rng = np.random.default_rng(_SEED + 1)
    # Same marginal distribution as the real treatment, no causal path.
    frame["trade_amount"] = rng.permutation(frame["trade_amount"].to_numpy())
    verdict = _fit(frame)
    assert verdict.beta is not None, verdict.reason
    assert abs(verdict.beta) < _TOL
    assert not verdict.trusted


def test_shuffled_outcome_collapses_the_effect() -> None:
    frame = reference_world(WORLD_B)
    rng = np.random.default_rng(_SEED + 2)
    frame["risk_score"] = rng.permutation(frame["risk_score"].to_numpy())
    verdict = _fit(frame)
    assert verdict.beta is not None, verdict.reason
    assert abs(verdict.beta) < _TOL
    assert not verdict.trusted


def test_the_same_request_is_allowed_in_one_world_and_denied_in_the_other() -> None:
    """Acceptance criterion: ALLOW vs DENY is traceable to the data alone."""
    gatekeeper = build_finance_causal_gatekeeper()
    # _marginal_risk's 0.5 baseline. This test encodes current behaviour and
    # changes with the separate enforcement finding.
    headroom = CAUSAL_LOCK_RISK_BOUNDARY - 0.5
    verdict_a = _fit(reference_world(WORLD_A))
    verdict_b = _fit(reference_world(WORLD_B))
    assert verdict_a.beta is not None and verdict_b.beta is not None
    trip_a = headroom * CAUSAL_NORMALIZATION_SCALE / verdict_a.beta
    trip_b = headroom * CAUSAL_NORMALIZATION_SCALE / verdict_b.beta
    assert trip_b < trip_a
    amount = (trip_a + trip_b) / 2.0  # between the two trip points
    in_a = gatekeeper.evaluate({"amount": amount}, verdict=verdict_a)
    in_b = gatekeeper.evaluate({"amount": amount}, verdict=verdict_b)
    assert (in_a.safe, in_a.reason) == (True, REASON_TRUSTED)
    assert (in_b.safe, in_b.reason) == (False, REASON_RISK_BOUNDARY)


