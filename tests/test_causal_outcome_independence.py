def test_recovery_band_rejects_the_calibration_constant() -> None:
    """Sensitivity check for the recovery contract, not a production property.

    A frame generated by the calibration formula (0.5 / 0.5) recovers
    beta ≈ 0.49. This asserts that such a value would *fail* the recovery band
    of every world used above, i.e. that the contract cannot be satisfied by a
    pipeline that merely reproduces the calibration constant.
    """
    verdict = _fit(reference_world(CALIBRATION_WORLD))
    assert verdict.beta is not None, verdict.reason
    assert (
        abs(verdict.beta - _CALIBRATION_BETA) < _TOL
    )  # the calibration recovers itself
    for truth in (WORLD_A, WORLD_B):
        assert abs(verdict.beta - truth.amount_coef) >= _TOL, (
            f"recovery band {_TOL} does not separate the calibration slope "
            f"{verdict.beta:.4f} from world {truth.amount_coef}"
        )


def test_self_certification_detector_flags_the_calibration_world() -> None:
    """Sensitivity check for the detector, not a production property: a frame
    generated by the calibration formula must be flagged, otherwise the
    tripwire is vacuous."""
    d = calibration_formula_distance(
        reference_world(CALIBRATION_WORLD, n=_DETECTOR_N, seed=_SEED + 4)
    )
    # reference_world adds a 0.05 intercept, so only the two slopes are the
    # calibration formula's. Check them directly.
    assert float(np.abs(d.z[1:]).max()) < _SELF_CERTIFICATION_Z, np.round(
        d.z, 1
    ).tolist()


# ---------------------------------------------------------------------------
# 3. Self-certification detector (the tripwire)
# ---------------------------------------------------------------------------


def _finance_synthetic_factory() -> pd.DataFrame:
    factory = build_finance_causal_spec().synthetic_telemetry_factory
    assert factory is not None
    return factory()  # called as production calls it: no arguments


def _mock_provider() -> pd.DataFrame:
    return MockTelemetryProvider(seed=_SEED).get_latest_data(_DETECTOR_N)


# Every source the causal tier can be wired to today. When an independent
# outcome observer lands it is added here, the xfail marker below is removed,
# and the assertion stays.
_CURRENT_SOURCES: dict[str, Callable[[], pd.DataFrame]] = {
    "finance_synthetic_telemetry": _finance_synthetic_factory,
    "kernel_mock_telemetry_provider": _mock_provider,
}


@pytest.mark.xfail(
    strict=True,
    raises=SelfCertifyingOutcome,
    reason=(
        "POAM-2026-094: both current telemetry sources emit the calibration "
        "formula (all three OLS coefficients within 1.73 SE of (0, 0.5, 0.5) at "
        "n = 1,000). Remove this marker, and only this marker, when an outcome "
        "observer that reads a realised quantity is wired in; the assertion is "
        "the permanent guard."
    ),
)
@pytest.mark.parametrize("source", sorted(_CURRENT_SOURCES))
def test_tier_telemetry_source_is_not_the_calibration_formula(source: str) -> None:
    frame = _CURRENT_SOURCES[source]()
    # A plain assertion, outside the marker's ``raises``: it fails outright.
    assert len(frame) == _DETECTOR_N, (
        f"{source} yields {len(frame)} rows; the {_SELF_CERTIFICATION_Z}-SE "
        f"threshold is calibrated at n = {_DETECTOR_N}. Re-measure before "
        "changing either (see the module docstring)."
    )
    d = calibration_formula_distance(frame)
    if d.is_calibration_formula:
        raise SelfCertifyingOutcome(
            f"{source}: the outcome IS the calibration formula. OLS coefficients "
            f"(intercept, vol, amount/scale) = {np.round(d.coef, 4).tolist()} are "
            f"all within {_SELF_CERTIFICATION_Z} SE of "
            f"{_CALIBRATION_FORMULA.tolist()} "
            f"(|z| = {np.round(np.abs(d.z), 1).tolist()}, R² = {d.r_squared:.3f}). "
            "The causal tier is validating a formula it was handed, not a world "
            "it observed."
        )


@pytest.mark.parametrize("truth", [WORLD_A, WORLD_B], ids=["0.8/0.2", "0.3/0.6"])
def test_self_certification_detector_passes_an_independent_world(
    truth: GroundTruth,
) -> None:
    """Control for the tripwire: a world that is *not* the calibration formula
    must clear the detector, so it can go green for the right reason and is not
    merely always red. These worlds have R² as high as the calibration
    sources', which is why R² is not the criterion."""
    d = calibration_formula_distance(reference_world(truth, n=_DETECTOR_N))
    assert not d.is_calibration_formula, (
        f"detector cannot distinguish world {truth} from the calibration formula "
        f"(|z| = {np.round(np.abs(d.z), 1).tolist()})"
    )
    assert float(np.abs(d.z).max()) > 2 * _SELF_CERTIFICATION_Z  # comfortable margin
